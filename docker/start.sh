#!/bin/sh
# Що відбувається при старті контейнера:
#   1. створюються таблиці (міграції Alembic)
#   2. база наповнюється прикладами — якщо вона порожня
#   3. піднімається застосунок
set -e

echo "→ Створюю таблиці…"
alembic upgrade head

echo "→ Наповнюю базу прикладами…"
python -m app.cli demo-data

echo "→ Запускаю застосунок…"
exec uvicorn app.main:app --host 0.0.0.0 --port 8000
